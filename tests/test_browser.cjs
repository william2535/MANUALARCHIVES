const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync(require('path').join(__dirname,'../index.html'),'utf8');
const elements=new Map();
for(const [,id] of html.matchAll(/\bid="([^"]+)"/g)) elements.set(id,{value:'',innerHTML:'',textContent:'',hidden:false,events:{},attrs:{},addEventListener(type,fn){this.events[type]=fn},setAttribute(k,v){this.attrs[k]=v}});
for(const [,id,json] of html.matchAll(/<script id="([^"]+)" type="application\/json">(.*?)<\/script>/gs))elements.get(id).textContent=json;
const location={hash:'#standards'},events={};
const context={document:{getElementById:id=>{assert(elements.has(id),`Missing element ${id}`);return elements.get(id)}},location,window:{addEventListener:(type,fn)=>events[type]=fn},console};
vm.createContext(context);
for(const [,js] of html.matchAll(/<script>(.*?)<\/script>/gs))vm.runInContext(js,context);
const standardData=JSON.parse(elements.get('standards-data').textContent), manualData=JSON.parse(elements.get('catalogue').textContent);
const el=id=>elements.get(id),change=(id,value)=>{el(id).value=value;el(id).events[id.endsWith('search')?'input':'change']()};
assert.equal(el('manual-panel').hidden,true);
assert.equal(el('standards-panel').hidden,false);
assert(el('count').textContent.includes(manualData.length.toLocaleString('en-US')));
assert(el('standards-count').textContent.startsWith(standardData.records.length+' references'));
assert.equal((el('standards-drafts').innerHTML.match(/<li>/g)||[]).length,standardData.draft_watchlist.length);
assert(!el('standards-results').innerHTML.includes('26/30563579 DC'));
change('standards-search','BS 7671 A4:2026');
assert.match(el('standards-count').textContent,/1 references/);
assert.match(el('standards-results').innerHTML,/2026-10-15/);
assert.match(el('standards-results').innerHTML,/A4:2026/);
assert.doesNotMatch(el('standards-results').innerHTML,/Open PDF/);
el('standards-clear').events.click();
change('standards-update','withdrawn');
assert(el('standards-count').textContent.startsWith(standardData.records.filter(r=>r.status==='withdrawn').length+' references'));
assert.match(el('standards-results').innerHTML,/BS 5839-2:1983/);
el('standards-clear').events.click();
change('standards-category','cctv');
assert(el('standards-count').textContent.startsWith(standardData.records.filter(r=>r.category==='cctv').length+' references'));
el('standards-clear').events.click();
const before=el('standards-results').innerHTML.match(/<article/g).length;
el('standards-more').events.click();
assert.equal(el('standards-results').innerHTML.match(/<article/g).length,before+25);
change('standards-search','nothing-matches-123');
assert.match(el('standards-results').innerHTML,/No matching/);
location.hash='#manuals';events.hashchange();
assert.equal(el('manual-panel').hidden,false);
assert.equal(el('standards-panel').hidden,true);
assert.equal(el('nav-manuals').attrs['aria-current'],'page');
change('search','Man-1099');
assert.match(el('count').textContent,/2 records/);
assert.match(el('results').innerHTML,/Duplicate listing/);
assert.match(el('results').innerHTML,/Revision \/ issue: Issue 04/);
el('clear').events.click();
change('category','warden-call');
assert(el('count').textContent.startsWith(manualData.filter(r=>r.category==='warden-call').length+' records'));
change('brand','Tynetec');
assert.match(el('results').innerHTML,/Advent XT/);
assert.doesNotMatch(el('results').innerHTML,/rescue assistance/i);
el('clear').events.click();
change('search','P-512243A');
assert.match(el('results').innerHTML,/DP51223AC/);
assert.match(el('results').innerHTML,/archive/i);
el('standards-clear').events.click();
change('standards-category','warden-call');
assert.match(el('standards-count').textContent,/7 references/);
assert.match(el('standards-results').innerHTML,/BS 8521-2:2020/);
assert.doesNotMatch(el('standards-results').innerHTML,/Open PDF/);
